def _validate_world_library_facades() -> None:
    """Require every family-facade export to have exactly one API tier."""
    problems: list[str] = []
    for module_name, tiers in WORLD_LIBRARY_FACADE_TIERS.items():
        classified = [name for names in tiers.values() for name in names]
        duplicates = sorted({name for name in classified if classified.count(name) > 1})
        exports = set(getattr(import_module(module_name), "__all__", ()))
        declared = set(classified)
        unclassified = sorted(exports - declared)
        stale = sorted(declared - exports)
        if duplicates:
            problems.append(f"{module_name} multiply classified: {', '.join(duplicates)}")
        if unclassified:
            problems.append(f"{module_name} unclassified exports: {', '.join(unclassified)}")
        if stale:
            problems.append(f"{module_name} classified names not exported: {', '.join(stale)}")
    if problems:
        raise RuntimeError("; ".join(problems))


def _validate_coverage() -> dict[str, tuple[str, str]]:
    """Return export locations after checking classification and alias coverage."""
    import archetype

    _validate_world_library_facades()

    framework_locations = dict(archetype._EXPORTS)
    framework_exports = set(archetype.__all__)
    if framework_exports != set(framework_locations):
        raise RuntimeError("framework __all__ and _EXPORTS disagree")
    supplemental_collisions = sorted(set(SUPPLEMENTAL) & framework_exports)
    if supplemental_collisions:
        raise RuntimeError(
            "supplemental locations collide with root exports: "
            + ", ".join(supplemental_collisions)
        )

    documented = {name for page in PAGES for name in page.names}
    top_level_documented = documented - set(SUPPLEMENTAL)
    actual = framework_exports
    missing = sorted(actual - top_level_documented)
    stale = sorted(top_level_documented - actual)
    duplicates = sorted(
        name for name in documented if sum(name in page.names for page in PAGES) > 1
    )
    if missing or stale or duplicates:
        problems = []
        if missing:
            problems.append(f"unclassified top-level exports: {', '.join(missing)}")
        if stale:
            problems.append(f"classified names not exported at top level: {', '.join(stale)}")
        if duplicates:
            problems.append(f"exports assigned more than once: {', '.join(duplicates)}")
        raise RuntimeError("; ".join(problems))

    return {**framework_locations, **SUPPLEMENTAL}


def _type_name(annotation: object) -> str:
    """Render a compact Python type name for a generated field table."""
    if annotation is Any:
        return "Any"
    if annotation is Ellipsis:
        return "..."
    if annotation is None or annotation is type(None):
        return "None"

    origin = get_origin(annotation)
    args = get_args(annotation)
    if origin is Annotated:
        return _type_name(args[0])
    if origin in (Union, types.UnionType):
        return " | ".join(_type_name(arg) for arg in args)
    if origin is not None:
        name = getattr(origin, "__name__", str(origin).replace("typing.", ""))
        if args:
            return f"{name}[{', '.join(_type_name(arg) for arg in args)}]"
        return name

    return getattr(annotation, "__name__", str(annotation).replace("typing.", ""))


def _default_name(default: object, factory: object | None, required: bool) -> str:
    if required:
        return "required"
    if factory is not None:
        name = getattr(factory, "__name__", type(factory).__name__)
        return f"generated by {name}"
    if isinstance(default, Enum):
        return repr(default.value)
    return repr(default)


def _escape_cell(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def _record_rows(record: type) -> list[tuple[str, str, str, str]]:
    if issubclass(record, Enum):
        return [(member.name, record.__name__, repr(member.value), "—") for member in record]

    model_fields = cast(dict[str, Any] | None, getattr(record, "model_fields", None))
    if model_fields is not None:
        rows = []
        for name, info in model_fields.items():
            rows.append(
                (
                    name,
                    _type_name(info.annotation),
                    _default_name(info.default, info.default_factory, info.is_required()),
                    info.description or "—",
                )
            )
        return rows

    if is_dataclass(record):
        rows = []
        for info in fields(record):
            required = info.default is MISSING and info.default_factory is MISSING
            factory = None if info.default_factory is MISSING else info.default_factory
            default = None if info.default is MISSING else info.default
            rows.append(
                (
                    info.name,
                    _type_name(info.type),
                    _default_name(default, factory, required),
                    "—",
                )
            )
        return rows

    return []


def _record_table(name: str, locations: dict[str, tuple[str, str]]) -> list[str]:
    module_name, attribute = locations[name]
    record = getattr(import_module(module_name), attribute)
    rows = _record_rows(record)
    if not rows:
        return []

    show_descriptions = any(description != "—" for *_, description in rows)
    lines = (
        ["| Field | Type | Default | Description |", "| --- | --- | --- | --- |"]
        if show_descriptions
        else ["| Field | Type | Default |", "| --- | --- | --- |"]
    )
    for field_name, annotation, default, description in rows:
        cells = [
            f"`{_escape_cell(field_name)}`",
            f"`{_escape_cell(annotation)}`",
            f"`{_escape_cell(default)}`",
        ]
        if show_descriptions:
            cells.append(_escape_cell(description))
        lines.append("| " + " | ".join(cells) + " |")
    lines.append("")
    return lines


def _directive(name: str, locations: dict[str, tuple[str, str]]) -> list[str]:
    module, attribute = locations[name]
    lines = [f"::: {module}.{attribute}"]
    options: list[str] = []
    members = EXPLICIT_MEMBERS.get(name)
    if members:
        options.append("      members:")
        options.extend(f"        - {member}" for member in members)
    elif name in RECORDS:
        options.append("      members: false")
    if name in HIDDEN_SIGNATURES:
        options.append("      show_signature: false")
    if options:
        lines.append("    options:")
        lines.extend(options)
    lines.append("")
    return lines


def _render_page(page: ReferencePage, locations: dict[str, tuple[str, str]]) -> str:
    lines = [
        GENERATED,
        "",
        f"# {page.title}",
        "",
        "| Package | Value |",
        "| --- | --- |",
        f"| Distribution | `{page.distribution}` |",
        f"| Import package | `{PACKAGE_IMPORTS[page.distribution]}` |",
        "",
        f"**{page.tier}.** {page.introduction}",
        "",
    ]
    for name in page.names:
        lines.extend(_directive(name, locations))
        if name in RECORDS:
            lines.extend(_record_table(name, locations))
    return "\n".join(lines)


