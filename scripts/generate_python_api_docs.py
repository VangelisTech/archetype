def _validate_coverage():
    import archetype

    names = [name for _title, group in PAGES.values() for name in group]
    if (
        len(names) != len(set(names))
        or set(names) != set(archetype.__all__)
        or set(archetype.__all__) != set(archetype._EXPORTS)
    ):
        raise RuntimeError("Every root export must have exactly one reference classification")
    return dict(archetype._EXPORTS)


def _symbol(name):
    import archetype

    value = getattr(archetype, name)
    lines = ["## " + name, "", "`from archetype import " + name + "`", ""]
    doc = inspect.getdoc(value)
    handle = name == "PreparedArtifacts" or name.startswith(
        (
            "RuntimeWorld",
            "SyncRuntimeWorld",
            "RuntimeProgram",
            "SyncRuntimeProgram",
            "RuntimeCut",
            "SyncRuntimeCut",
            "RuntimeArtifacts",
            "SyncRuntimeArtifacts",
        )
    )
    if doc and not (handle and doc.startswith(name + "(")):
        lines.extend([doc, ""])
    if handle:
        lines.extend(
            [
                "Obtain this handle from the runtime or a completed operation. Its private constructor is not a supported interface.",
                "",
            ]
        )
    elif callable(value):
        try:
            lines.extend(["```python", name + str(inspect.signature(value)), "```", ""])
        except (ValueError, TypeError):
            pass
    if is_dataclass(value):
        public = [field for field in fields(value) if not field.name.startswith("_")]
        if public:
            lines.extend(["| Field | Type |", "| --- | --- |"])
            lines.extend(
                "| `" + field.name + "` | `" + str(field.type).replace("|", "\\|") + "` |"
                for field in public
            )
            lines.append("")
    if inspect.isclass(value):
        for method_name, member in inspect.getmembers(value):
            if method_name.startswith("_") or not callable(member):
                continue
            if method_name not in value.__dict__:
                continue
            try:
                signature = str(inspect.signature(member))
            except (ValueError, TypeError):
                continue
            lines.extend(
                ["### " + method_name, "", "```python", method_name + signature, "```", ""]
            )
            documentation = inspect.getdoc(member)
            if documentation:
                lines.extend([documentation, ""])
    return lines


def _expected_outputs(_locations=None):
    outputs = {}
    index = [
        GENERATED,
        "",
        "# Python API",
        "",
        "This is the supported 0.7 facade. Native Host, raw C ABI requests and concrete storage/runtime owners are private operator machinery. Required live cells are exact Int64, string, Bool and finite Float64. File ingestion and offline analytical contracts require the analysis extra.",
        "",
        "| Reference | Exports |",
        "| --- | --- |",
    ]
    for slug, (title, names) in PAGES.items():
        index.append(
            "| ["
            + title
            + "](python/"
            + slug
            + ".md) | "
            + ", ".join("`" + n + "`" for n in names)
            + " |"
        )
        page = [GENERATED, "", "# " + title, ""]
        if slug == "artifacts":
            page.extend(
                [
                    "These retained contracts serve offline ingestion and analysis. They do not install a second live execution owner. Smol remains independent.",
                    "",
                ]
            )
        for name in names:
            page.extend(_symbol(name))
        outputs[DOCS_DIR / "python" / (slug + ".md")] = "\n".join(page)
    outputs[DOCS_DIR / "python-api.md"] = "\n".join(index)
    return outputs


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    outputs = _expected_outputs(_validate_coverage())
    drift = [
        str(path.relative_to(ROOT))
        for path, body in outputs.items()
        if not path.is_file() or path.read_text() != body
    ]
    if args.check:
        if drift:
            print("Python reference drift: " + ", ".join(drift))
            return 1
        print("Supported 0.7 Python reference is current")
        return 0
    for path, body in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
