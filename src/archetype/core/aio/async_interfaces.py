from typing import  List,  Tuple, Protocol, Type, Optional
from daft import DataFrame

from archetype.core import ArchetypeSignature, Component
from archetype.core.config import RunConfig

class iAsyncStore(Protocol):
    async def get_archetype_df(self, sig: ArchetypeSignature, world_id: str, run_id: str) -> DataFrame: ...
    async def append(self, sig: ArchetypeSignature, df: DataFrame) -> None: ...
    async def shutdown(self) -> None: ...
class iAsyncQueryManager(Protocol):
    async def get_archetype(self, sig: ArchetypeSignature, world_id: str, run_id: str) -> DataFrame: ...
    async def query_archetype(self, sig: ArchetypeSignature, world_id: str, run_id: str, ticks: Optional[List[int]] = None, entity_ids: Optional[List[int]] = None, components: Optional[List[Component]] = None) -> DataFrame: ...

class iAsyncUpdateManager(Protocol):
    async def update(self, df: DataFrame, sig: ArchetypeSignature, tick: int, world_id: str, run_id: str) -> DataFrame: ...
    # async def validate(self, df: DataFrame, sig: ArchetypeSignature): ...
class iAsyncProcessor(Protocol):
    async def process(self, df: DataFrame, **input_kwargs) -> DataFrame: ...

class iAsyncSystem(Protocol):
    async def add_processor(self, proc: iAsyncProcessor) -> None: ...
    async def remove_processor(self, proc_type: Type[iAsyncProcessor]) -> None: ...
    async def execute(self, df: DataFrame, sig: ArchetypeSignature, **input_kwargs) -> DataFrame: ...

class iAsyncWorld(Protocol):
    async def run(self, run_config: RunConfig, **input_kwargs) -> None: ...
    async def step(self, **input_kwargs) -> None: ...
    async def _run_archetype(self, sig: ArchetypeSignature, **input_kwargs) -> Tuple[DataFrame, ArchetypeSignature]: ...
    def materialize_mutations(self, df: DataFrame, sig: ArchetypeSignature) -> DataFrame: ...
    @property
    def active_signatures(self) -> Tuple[Type[Component], ...]: ...
    async def create_entity(self, components: List[Component]) -> int: ...
    async def remove_entity(self, entity_id: int) -> None: ...
    async def add_components(self, entity_id: int, components: List[Component]) -> None: ...
    async def remove_components(self, entity_id: int, component_types: List[Type[Component]]) -> None: ...
    async def add_processor(self, proc: iAsyncProcessor) -> None: ...
    async def remove_processor(self, proc_type: Type[iAsyncProcessor]) -> None: ...
    async def query_archetype(self, sig: ArchetypeSignature, ticks: Optional[List[int]] = None, entity_ids: Optional[List[int]] = None, components: Optional[List[Component]] = None, run_config: Optional[RunConfig] = None) -> DataFrame: ...
    async def get_components(self, components: List[Component], entity_ids: Optional[List[int]] = None) -> DataFrame: ...
    async def execute(self, df: DataFrame, sig: ArchetypeSignature, **input_kwargs) -> DataFrame: ...
    async def update(self, df: DataFrame, sig: ArchetypeSignature, tick: int | None = None) -> None: ...
