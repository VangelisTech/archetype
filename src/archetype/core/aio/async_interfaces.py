from typing import  List,  Tuple, Protocol, Type
import asyncio
from daft import DataFrame

from archetype.core import ArchetypeSignature, Component

class iAsyncStore(Protocol):
    async def get_archetype_df(self, sig: ArchetypeSignature, tick: int, world_id: str, run_id: str) -> DataFrame: ...
    async def append(self, sig: ArchetypeSignature, df: DataFrame, tick: int, world_id: str, run_id: str) -> None: ...
    async def shutdown(self) -> None: ...
class iAsyncQueryManager(Protocol):
    async def get_archetype(self, sig: ArchetypeSignature, tick: int, world_id: str, run_id: str) -> Tuple[ArchetypeSignature, DataFrame]: ...
    async def query_archetype(self, entity_id: int, sig: ArchetypeSignature, tick: int, world_id: str, run_id: str) -> DataFrame: ...

class iAsyncUpdateManager(Protocol):
    async def update(self, df: DataFrame, sig: ArchetypeSignature, tick: int, world_id: str, run_id: str) -> None: ...
    # async def validate(self, df: DataFrame, sig: ArchetypeSignature): ...
class iAsyncProcessor(Protocol):
    async def process(self, df: DataFrame, **kwargs) -> DataFrame: ...

class iAsyncSystem(Protocol):
    async def add_processor(self, proc: iAsyncProcessor) -> None: ...
    async def remove_processor(self, proc: iAsyncProcessor) -> None: ...
    async def execute(self, querier: iAsyncQueryManager, tick: int, *args, **kwargs) -> List[Tuple[ArchetypeSignature, DataFrame]]: ...

class iAsyncWorld(Protocol):
    async def step(self, **kwargs): ...
    def materialize_mutations(self, df: DataFrame, sig: ArchetypeSignature): ...
    async def create_entity(self, components: List[Component]) -> int: ...
    async def remove_entity(self, entity_id: int): ...
    async def add_components(self, entity_id: int, components: List[Component]) -> None: ...
    async def add_processor(self, proc: iAsyncProcessor) -> None: ...
    async def remove_components(self, entity_id: int, component_types: List[Type[Component]]) -> None: ...
    async def remove_processor(self, proc: iAsyncProcessor) -> None: ...
    async def query_archetype(self, entity_id: int, *component_types: Type[Component]) -> DataFrame: ...
    async def execute(self, df: DataFrame, sig: ArchetypeSignature, tick: int, *args, **kwargs) -> DataFrame: ...
    async def update(self, archetypes: List[Tuple[ArchetypeSignature, DataFrame]]) -> None: ...
